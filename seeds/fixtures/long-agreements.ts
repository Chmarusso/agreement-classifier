type Clause = [title: string, subclauses: string[]];

function clauses(list: Clause[], start = 1): string {
  return list
    .map(([title, subs], i) => {
      const n = start + i;
      return [`## ${n}. ${title}`, ...subs.map((s, j) => `${n}.${j + 1} ${s}`)].join("\n\n");
    })
    .join("\n\n");
}

function schedule(n: number, title: string, body: string): string {
  return `# Schedule ${n}: ${title}\n\n${body}`;
}

function scheduleClauses(n: number, subs: string[]): string {
  return subs.map((s, j) => `${n}.${j + 1} ${s}`).join("\n\n");
}

function table(header: string[], rows: string[][]): string {
  return [`| ${header.join(" | ")} |`, `| ${header.map(() => "---").join(" | ")} |`, ...rows.map((r) => `| ${r.join(" | ")} |`)].join("\n");
}


/**
 * Real-length fixtures (20-30 pages as PDF). Each is written as markdown:
 *   "## N. Title" for clauses, "N.M text" paragraphs for sub-clauses,
 *   "# Schedule N: Title" for schedules (numbering restarts), and pipe tables.
 * The long PDF renderer adds a table of contents, running headers and page footers.
 */

